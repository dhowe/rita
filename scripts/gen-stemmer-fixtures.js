#!/usr/bin/env node
/**
 * Extracts the stemmer input/expected pairs from js/test/stemmer-tests.js into
 * shared/stemmer-fixtures.json so the Java suite can be driven from data instead of
 * duplicating ~6400 lines of test("word", "stem") calls.
 *
 *   node scripts/gen-stemmer-fixtures.js
 *
 * js/test/stemmer-tests.js stays the source of truth: the Java test asserts the same
 * pairs, in the same order, grouped by the same it() block names.
 */

import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { join, dirname } from 'path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'js', 'test', 'stemmer-tests.js');
const target = join(root, 'shared', 'stemmer-fixtures.json');

const text = readFileSync(source, 'utf8');

// Split into it() blocks so the Java test can mirror the same grouping.
const blocks = [];
const blockRe = /it\('([^']+)', function \(\) \{([\s\S]*?)\n  \}\);/g;
let block;
while ((block = blockRe.exec(text)) !== null) {
  const body = block[2];
  const pairs = [];
  const pairRe = /test\("((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\);?/g;
  let pair;
  while ((pair = pairRe.exec(body)) !== null) {
    pairs.push([decode(pair[1]), decode(pair[2])]);
  }
  if (pairs.length) {
    blocks.push({ name: block[1], pairs });
  }
}

// The stemAll block asserts RiTa.Stemmer.stemAll() over a whole array, not per-word.
const stemAll = (() => {
  const m = text.match(/it\('Should call stemAll'[\s\S]*?let input = (\[[^\]]*\]);[\s\S]*?let expected = (\[[^\]]*\]);/);
  if (!m) return null;
  return { input: JSON.parse(m[1]), expected: JSON.parse(m[2]) };
})();

if (!stemAll) {
  throw new Error('Could not locate the stemAll block in ' + source);
}

const total = blocks.reduce((n, b) => n + b.pairs.length, 0);
const doc = {
  _comment: 'Generated by scripts/gen-stemmer-fixtures.js from js/test/stemmer-tests.js. Do not edit by hand.',
  stem: blocks.filter((b) => b.name !== 'Should call stemAll'),
  stemAll,
};

writeFileSync(target, JSON.stringify(doc, null, 1) + '\n', 'utf8');
console.log(`Written: ${target}`);
console.log(`  ${blocks.length} blocks, ${total} stem pairs, stemAll: ${stemAll.input.length} words`);

/** Converts a JS string literal body into its runtime value. */
function decode(s) {
  return s.replace(/\\(.)/g, (_, c) => (c === 'n' ? '\n' : c === 't' ? '\t' : c));
}
