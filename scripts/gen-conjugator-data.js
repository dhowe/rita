#!/usr/bin/env node
/*
 * Generates java/src/main/java/rita/{ConjugatorData,InflectorData}.java from the JS
 * ground-truth tables in js/src/{conjugator,inflector}.js.
 *
 * The tables are pure data (word lists + regex rules). We evaluate the JS modules in a
 * sandbox to read the live objects, then emit Java so the port is byte-identical to JS
 * without hand-transcribing thousands of entries.
 *
 * Usage: node scripts/gen-conjugator-data.js
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const javaDir = path.join(root, 'java/src/main/java/rita');

function readModule(file, prelude, exportsList) {
  let src = fs.readFileSync(path.join(root, 'js/src', file), 'utf8');
  // Drop the ES import line(s) and the export default tail; provide shims instead.
  src = src.replace(/^import[^\n]*\n/gm, '');
  src = src.replace(/export\s+default[\s\S]*$/, '');
  const fn = new Function((prelude || '') + '\n' + src + '\nreturn {' + exportsList + '};');
  return fn();
}

// ---- sandbox shims -------------------------------------------------------------
// conjugator.js is self-contained (defines its own RegularExpression/RE).
const conjugator = readModule('conjugator.js', '',
  'IRREG_VERBS_LEX,IRREG_VERBS_NOLEX,IRREG_PAST_PART,VERB_CONS_DOUBLING,' +
  'PAST_PART_RULES,PAST_RULES,PRESENT_RULES,ING_FORM_RULES,TO_BE,MODALS');

// inflector.js imports Util.RE; shim it so RE(...) yields {raw,offset,suffix}.
const inflector = readModule('inflector.js',
  'const Util = { RE: (raw, offset, suffix) => ({ raw, offset, suffix: suffix || "" }) };',
  'SING_RULES,PLUR_RULES,IS_PLURAL_RULES');

// ---- Java emission helpers -----------------------------------------------------
function jstr(s) {
  let out = '"';
  for (const ch of s) {
    if (ch === '\\') out += '\\\\';
    else if (ch === '"') out += '\\"';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else out += ch;
  }
  return out + '"';
}

function ruleArray(name, rules) {
  const lines = [`    static final RE[] ${name} = {`];
  rules.forEach((r, i) => {
    const comma = i < rules.length - 1 ? ',' : '';
    // JS RE(regex) with no offset: truncate does substr(0, len - undefined) = substr(0, NaN) = "",
    // so emit a sentinel offset that makes RE.truncate return "" for any word.
    const off = (r.offset === undefined) ? 'Integer.MAX_VALUE' : r.offset;
    lines.push(`        new RE(${jstr(r.raw)}, ${off}, ${jstr(r.suffix)})${comma}`);
  });
  lines.push('    };');
  return lines.join('\n');
}

function wordList(name, words) {
  const lines = [`    static final String[] ${name} = {`];
  for (let i = 0; i < words.length; i += 1) {
    const comma = i < words.length - 1 ? ',' : '';
    lines.push(`        ${jstr(words[i])}${comma}`);
  }
  lines.push('    };');
  return lines.join('\n');
}

function mapEntries(name, obj) {
  const keys = Object.keys(obj);
  const lines = [`    static final String[][] ${name} = {`];
  keys.forEach((k, i) => {
    const comma = i < keys.length - 1 ? ',' : '';
    lines.push(`        { ${jstr(k)}, ${jstr(obj[k])} }${comma}`);
  });
  lines.push('    };');
  return lines.join('\n');
}

const header = (cls, note) =>
  `package rita;\n\n` +
  `/**\n * ${note}\n *\n` +
  ` * <p>Generated by <code>scripts/gen-conjugator-data.js</code> from the JS ground truth in\n` +
  ` * <code>js/src/</code>. Do not edit by hand \u2014 regenerate instead.\n */\n` +
  `final class ${cls} {\n\n    private ${cls}() {\n    }\n\n` +
  (cls === "ConjugatorData"
    ? `    /** Builds a lookup map from a {@code [key, value]} pair array. */\n`
      + `    static java.util.Map<String, String> mapOf(String[][] pairs) {\n`
      + `        java.util.Map<String, String> m = new java.util.LinkedHashMap<>();\n`
      + `        for (String[] p : pairs) {\n            m.put(p[0], p[1]);\n        }\n`
      + `        return m;\n    }\n\n`
    : "");

// ---- ConjugatorData ------------------------------------------------------------
let conj = header('ConjugatorData',
  'Static verb tables for {@link Conjugator} \u2014 irregular verbs, doubling stems, and regex conjugation rule sets.');

conj += mapEntries('IRREG_VERBS_LEX', conjugator.IRREG_VERBS_LEX) + '\n\n';
conj += mapEntries('IRREG_VERBS_NOLEX', conjugator.IRREG_VERBS_NOLEX) + '\n\n';
conj += wordList('IRREG_PAST_PART', conjugator.IRREG_PAST_PART) + '\n\n';
conj += wordList('VERB_CONS_DOUBLING', conjugator.VERB_CONS_DOUBLING) + '\n\n';
conj += wordList('MODALS', conjugator.MODALS) + '\n\n';
conj += wordList('TO_BE', conjugator.TO_BE) + '\n\n';
conj += ruleArray('ING_FORM_RULES', conjugator.ING_FORM_RULES) + '\n\n';
conj += ruleArray('PAST_PART_RULES', conjugator.PAST_PART_RULES) + '\n\n';
conj += ruleArray('PAST_RULES', conjugator.PAST_RULES) + '\n\n';
conj += ruleArray('PRESENT_RULES', conjugator.PRESENT_RULES) + '\n';
conj += '\n}\n';

// ---- InflectorData -------------------------------------------------------------
let infl = header('InflectorData',
  'Static noun tables for {@link Inflector} \u2014 the singular/plural rule sets and isPlural test regexes.');

infl += ruleArray('SING_RULES', inflector.SING_RULES) + '\n\n';
infl += ruleArray('PLUR_RULES', inflector.PLUR_RULES) + '\n\n';
// IS_PLURAL_RULES are raw RegExp literals (not RE wrappers) — use their source.
const ipr = inflector.IS_PLURAL_RULES.map(r => (r.source !== undefined ? r.source : r.raw));
infl += wordList('IS_PLURAL_RULES', ipr) + '\n';
infl += '\n}\n';

fs.writeFileSync(path.join(javaDir, 'ConjugatorData.java'), conj);
fs.writeFileSync(path.join(javaDir, 'InflectorData.java'), infl);

// ---- sanity report -------------------------------------------------------------
console.log('IRREG_VERBS_LEX :', Object.keys(conjugator.IRREG_VERBS_LEX).length);
console.log('IRREG_VERBS_NOLEX:', Object.keys(conjugator.IRREG_VERBS_NOLEX).length);
console.log('IRREG_PAST_PART :', conjugator.IRREG_PAST_PART.length);
console.log('VERB_CONS_DOUBLING:', conjugator.VERB_CONS_DOUBLING.length);
console.log('ING_FORM_RULES  :', conjugator.ING_FORM_RULES.length);
console.log('PAST_PART_RULES :', conjugator.PAST_PART_RULES.length);
console.log('PAST_RULES      :', conjugator.PAST_RULES.length);
console.log('PRESENT_RULES   :', conjugator.PRESENT_RULES.length);
console.log('SING_RULES      :', inflector.SING_RULES.length);
console.log('PLUR_RULES      :', inflector.PLUR_RULES.length);
console.log('IS_PLURAL_RULES :', ipr.length);
console.log('Wrote ConjugatorData.java + InflectorData.java');
